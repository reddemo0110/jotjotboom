    /// Lit pixels as (x, y) in a 16×16 grid.
    pub fn pixels(self) -> impl Iterator<Item = (u8, u8)> {
        self.rows().into_iter().enumerate().flat_map(|(y, row)| {
            row.bytes()
                .enumerate()
                .filter(|(_, b)| *b == b'#')
                .map(move |(x, _)| (x as u8, y as u8))
        })
    }

    /// An SVG of the glyph in `color`, crisp-edged.
    pub fn svg(self, color: Color) -> String {
        let fill = format!(
            "#{:02x}{:02x}{:02x}",
            (color.r * 255.0).round() as u8,
            (color.g * 255.0).round() as u8,
            (color.b * 255.0).round() as u8
        );
        let mut out = String::from(
            "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 16 16\" shape-rendering=\"crispEdges\">",
        );
        for (x, y) in self.pixels() {
            out.push_str(&format!(
                "<rect x=\"{x}\" y=\"{y}\" width=\"1\" height=\"1\" fill=\"{fill}\"/>"
            ));
        }
        out.push_str("</svg>");
        out
    }
